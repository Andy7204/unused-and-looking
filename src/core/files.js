// Which files we read, which language they are, and what role they play.
// Paths are always POSIX-style and relative to the scanned root.

export const SOURCE_EXT = {
  '.js': 'js', '.mjs': 'js', '.cjs': 'js', '.jsx': 'js',
  '.ts': 'js', '.tsx': 'js', '.mts': 'js', '.cts': 'js',
  '.py': 'py',
  '.go': 'go',
  '.rb': 'rb', '.rake': 'rb', '.gemspec': 'rb',
};

// Templates: anything written here really is a call (onclick="foo()", {{ foo() }}).
export const TEMPLATE_EXT = new Set([
  '.html', '.htm', '.vue', '.svelte', '.astro', '.erb', '.haml', '.slim', '.ejs',
  '.hbs', '.handlebars', '.mustache', '.njk', '.jinja', '.jinja2', '.j2', '.liquid',
  '.twig', '.pug', '.tmpl', '.gohtml', '.jbuilder', '.php', '.mdx',
]);

// Config/data: a mention here *might* be a hook (entry points, cron jobs...).
export const CONFIG_EXT = new Set(['.json', '.yml', '.yaml', '.toml', '.cfg', '.ini', '.xml', '.conf', '.env']);
export const CONFIG_NAMES = new Set(['Procfile', 'Makefile', 'Dockerfile', 'Rakefile', 'Gemfile', 'Justfile', 'Taskfile']);

export const SKIP_DIRS = new Set([
  'node_modules', '.git', '.hg', '.svn', 'vendor', 'venv', '.venv', 'virtualenv', 'env.d',
  'dist', 'build', '.next', '.nuxt', '.svelte-kit', '.output', 'coverage', '.nyc_output',
  '__pycache__', '.tox', '.mypy_cache', '.pytest_cache', '.ruff_cache', 'site-packages',
  'bower_components', 'jspm_packages', '.yarn', '.pnpm-store', '.cache', '.parcel-cache',
  '.turbo', '.vercel', '.idea', '.vscode', 'third_party', 'third-party', 'Pods', '.bundle',
  // test fixtures & snapshots: code that exists to be *looked at*, not called
  'fixtures', '__fixtures__', 'fixture', 'testdata', '__snapshots__', '__mocks__',
]);

const SKIP_FILES = /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|npm-shrinkwrap\.json|Gemfile\.lock|go\.sum|poetry\.lock|Pipfile\.lock|composer\.lock|bun\.lockb?)$/;
const MINIFIED_NAME = /[.-](min|bundle|packed|compiled)\.[cm]?js$/i;
const GENERATED_NAME = /(\.d\.[cm]?ts$|\.test-d\.[cm]?tsx?$|\.pb\.go$|_pb2(_grpc)?\.py$|\.generated\.|_generated\.go$|\.gen\.go$|bindata\.go$|zz_generated)/;

export const MAX_FILE_BYTES = 750_000;

export function extname(p) {
  const base = p.slice(p.lastIndexOf('/') + 1);
  const dot = base.lastIndexOf('.');
  return dot > 0 ? base.slice(dot).toLowerCase() : '';
}

export function basename(p) {
  return p.slice(p.lastIndexOf('/') + 1);
}

export function dirname(p) {
  const i = p.lastIndexOf('/');
  return i === -1 ? '' : p.slice(0, i);
}

/** True if a directory name should never be entered. */
export function isSkippedDir(name) {
  return SKIP_DIRS.has(name) || name.endsWith('.egg-info');
}

/** True if any segment of a relative path is a skipped directory. */
export function isSkippedPath(relPath) {
  const parts = relPath.split('/');
  for (let i = 0; i < parts.length - 1; i++) if (isSkippedDir(parts[i])) return true;
  return SKIP_FILES.test(relPath);
}

/**
 * Classify a path. Returns { kind: 'source'|'template'|'config'|null, lang }.
 * `null` kind means we don't read it at all.
 */
export function classifyPath(relPath) {
  if (isSkippedPath(relPath)) return { kind: null };
  const ext = extname(relPath);
  const base = basename(relPath);
  if (SOURCE_EXT[ext]) {
    if (MINIFIED_NAME.test(base) || GENERATED_NAME.test(relPath)) return { kind: null };
    return { kind: 'source', lang: SOURCE_EXT[ext] };
  }
  if (base === 'Rakefile' || base === 'Gemfile' || base === 'Guardfile') return { kind: 'source', lang: 'rb' };
  if (TEMPLATE_EXT.has(ext)) return { kind: 'template' };
  if (CONFIG_EXT.has(ext) || CONFIG_NAMES.has(base)) return { kind: 'config' };
  return { kind: null };
}

/** Content-based skip: minified bundles and generated files. */
export function looksMinifiedOrGenerated(content, lang) {
  if (!content) return false;
  const head = content.slice(0, 600);
  if (/(Code generated .* DO NOT EDIT|@generated|auto-generated|autogenerated by|DO NOT EDIT)/i.test(head)) return true;
  if (lang !== 'js') return false;
  const lines = content.split('\n');
  if (lines.length < 4 && content.length > 3000) return true;
  let long = 0;
  for (const l of lines) if (l.length > 1000) long++;
  return long > 0 && long / lines.length > 0.05;
}

export function isTestFile(p, lang) {
  const base = basename(p);
  const segs = '/' + p;
  if (lang === 'js') return /\.(test|spec|e2e|cy)\.[cm]?[jt]sx?$/.test(base) || /\/(__tests__|tests?|e2e|cypress|playwright)\//.test(segs);
  if (lang === 'py') return /^test_.*\.py$|_tests?\.py$|^conftest\.py$/.test(base) || /\/tests?\//.test(segs);
  if (lang === 'go') return /_test\.go$/.test(base);
  if (lang === 'rb') return /_(spec|test)\.rb$/.test(base) || /\/(spec|test)\//.test(segs);
  return false;
}

/** Framework route files whose exports are called by the framework, not by you. */
export function isRouteFile(p) {
  const base = basename(p);
  if (/^\+(page|layout|server|error)(\.server)?\.[cm]?[jt]sx?$/.test(base)) return true; // SvelteKit
  if (/^(page|layout|route|loading|error|not-found|template|default|middleware|instrumentation|global-error|head|opengraph-image|twitter-image|icon|apple-icon|sitemap|robots|manifest)\.[cm]?[jt]sx?$/.test(base)) return true; // Next.js app router
  return /(^|\/)(pages|app\/routes|routes|api|functions|netlify\/functions|lambdas?)\//.test(p) && /\.[cm]?[jt]sx?$/.test(base);
}

export function isConfigScript(p) {
  const base = basename(p);
  return /\.config\.[cm]?[jt]s$/.test(base) ||
    /^(\.eslintrc|\.prettierrc|\.babelrc|\.mocharc|\.storybook|gulpfile|gruntfile|webpack\..*|rollup\..*|jest\.setup|vitest\.setup|setupTests|babel\.config|metro\.config|karma\.conf|protractor\.conf|svelte\.config|astro\.config|nuxt\.config|remix\.config)/i.test(base) ||
    /(^|\/)\.storybook\//.test(p);
}

export function isStoryFile(p) {
  return /\.stories\.[cm]?[jt]sx?$|\.story\.[cm]?[jt]sx?$/.test(p);
}
