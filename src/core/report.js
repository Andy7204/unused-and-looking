// Exports: Breakup List markdown, README badge, stats sentence, share text.
// The tool never edits code. These are just lists for a human to act on.

import { buildProfile, fmtNum, loneliest } from './profile.js';

export const HOMEPAGE = 'https://github.com/Andy7204/unused-and-looking';
export const DEMO_URL = 'https://andy7204.github.io/unused-and-looking/';

/** Link to a file on GitHub if we know the repo, else plain path. */
export function locationLink(o, repo, ref = 'HEAD') {
  const label = `${o.file}:${o.line}`;
  if (!repo) return '`' + label + '`';
  const enc = o.file.split('/').map(encodeURIComponent).join('/');
  return `[${label}](https://github.com/${repo}/blob/${ref}/${enc}#L${o.line}${o.endLine && o.endLine !== o.line ? '-L' + o.endLine : ''})`;
}

/**
 * @param {Array} breakups   orphans to delete
 * @param {{ repo?:string, ref?:string, complicated?:Array, now?:number, sourceLabel?:string }} opts
 */
export function breakupMarkdown(breakups, opts = {}) {
  const now = opts.now ?? Date.now();
  const lines = breakups.reduce((s, o) => s + o.length, 0);
  const out = [];
  out.push(`# 💔 Breakup List: ${breakups.length} function${breakups.length === 1 ? '' : 's'} we're letting go`);
  out.push('');
  out.push(`${opts.sourceLabel ? `Codebase: **${opts.sourceLabel}** · ` : ''}${fmtNum(lines)} line${lines === 1 ? '' : 's'} of loneliness · generated by [Unused & Looking](${HOMEPAGE})`);
  out.push('');
  out.push('> Nothing was deleted automatically. Before removing each one, search for dynamic uses (reflection, string lookups, other repos).');
  out.push('');
  const item = (o) => {
    const p = buildProfile(o, now);
    const age = p.days != null ? ` · single for ${fmtNum(p.days)} days` : '';
    const rows = [`- [ ] \`${o.name}()\` in ${locationLink(o, opts.repo, opts.ref)} · ${o.length} line${o.length === 1 ? '' : 's'} · ${o.confidence}% sure${age}`];
    rows.push(`  - Why: ${o.reasons.join('; ')}`);
    if (o.risks && o.risks.length) rows.push(`  - Double-check: ${o.risks.map((r) => r.text).join('; ')}`);
    const twin = (o.matches || []).find((m) => m.type === 'twin' || m.type === 'inline');
    if (twin) rows.push(`  - Possible duplicate: \`${twin.file}:${twin.line}\` (${twin.score}% similar)`);
    return rows.join('\n');
  };
  if (breakups.length) {
    out.push('## Delete');
    out.push('');
    for (const o of breakups) out.push(item(o));
    out.push('');
  }
  if (opts.complicated && opts.complicated.length) {
    out.push("## It's complicated (review later)");
    out.push('');
    for (const o of opts.complicated) out.push(item(o));
    out.push('');
  }
  out.push('---');
  out.push(`Find your own lonely functions: \`npx unused-and-looking\` · [swipe in the browser](${DEMO_URL})`);
  return out.join('\n') + '\n';
}

export function badgeUrl(count) {
  const color = count === 0 ? '2ecc71' : count < 10 ? 'ff8a5c' : 'ff4f8b';
  return `https://img.shields.io/badge/lonely%20functions-${count}-${color}`;
}

export function badgeMarkdown(count) {
  return `[![lonely functions: ${count}](${badgeUrl(count)})](${HOMEPAGE})`;
}

export function statsSentence(report) {
  const n = report.stats.orphans;
  if (n === 0) return 'Your codebase is happily married. 0 lonely functions.';
  return `Your codebase has ${fmtNum(n)} single function${n === 1 ? '' : 's'}. ${fmtNum(report.stats.lonelyLines)} line${report.stats.lonelyLines === 1 ? '' : 's'} of loneliness.`;
}

export function shareText(report, now = Date.now()) {
  const n = report.stats.orphans;
  if (!n) return 'My codebase has 0 lonely functions. Every function is in a happy relationship 💍';
  const o = loneliest(report.orphans, now);
  const p = buildProfile(o, now);
  const age = p.days != null ? `has been single for ${fmtNum(p.days)} days` : 'has never been called';
  return `My codebase has ${fmtNum(n)} lonely function${n === 1 ? '' : 's'}. The loneliest, ${o.name}(), ${age} 💔 Swipe through yours:`;
}
